"""Ambience rule persistence in ``audio.db`` (T-1238-C3.10).

Ambience definitions are APPLICATION-global audio configuration, so they
live in ``audio.db`` beside the sound presets -- never in a profile DB.

What is persisted is the RULE: enabled, sound ref, volume, trigger, schedule,
weekdays, weather condition, repeat, interval and fades, under a stable id.
What is never persisted is anything transient: the active channel handle, the
fade position, an in-flight weather request or a timer object.
"""

from __future__ import annotations

import json
import os
import sqlite3
import threading
import uuid

from fastprompter.core.ambience_engine import (
    DEFAULT_FADE_MS,
    REPEAT_LOOP,
    TRIGGER_ALWAYS,
    AmbienceRule,
)

AMBIENCE_DB_NAME = "audio.db"
AMBIENCE_TABLE = "ambience_rules_v1"

#: Location + opt-in for the weather trigger.  Weather is OFF until the user
#: configures a place: FastPrompter never geolocates anyone silently.
WEATHER_SETTINGS_TABLE = "ambience_settings_v1"
SETTING_WEATHER_ENABLED = "weather_enabled"
SETTING_WEATHER_LABEL = "weather_label"
SETTING_WEATHER_LAT = "weather_latitude"
SETTING_WEATHER_LON = "weather_longitude"

#: Does the user WANT ambience running?  This is a DESIRED state, not a
#: runtime one: it changes only when the user explicitly starts or stops
#: ambience, and it is what a fresh application session restores.  It is
#: application-global (audio.db, beside the rules) rather than per-profile,
#: so switching profile never silently turns the user's ambience off.
#:
#: Deliberately NOT written by shutdown or by STOP ALL SOUND.  Both of those
#: silence the CURRENT runtime; treating them as "the user stopped ambience"
#: would mean one press of STOP ALL quietly disabled ambience for every
#: future launch.
SETTING_RUNTIME_ENABLED = "runtime_enabled"


def new_rule_id() -> str:
    return f"amb_{uuid.uuid4().hex[:12]}"


#: Stable id for the shipped default (T-1455): the operator's requested
#: starting ambience -- one enabled loop at 0.01, always looping.
DEFAULT_AMBIENCE_RULE_ID = "amb_default_computalk1"

#: The file the default plays.  It MUST name a sound the app actually
#: ships, and ``tests/test_t1455_computalk1_default.py`` proves that against
#: the packaged tree alone.
#:
#: History: the default used to play ``computalk1.wav``.  Commit 81088e36
#: deleted that file as ``KNOWN_UNLICENSED_THIRD_PARTY`` and remapped
#: ``default_profile``/``sound_manager`` but not this module, so every fresh
#: install seeded a rule pointing at nothing and the ambience bed was silent
#: (T-1501).  The replacement is generated by
#: ``tools/generate_redistributable_sounds.py`` from original synthesis, so it
#: is redistributable and byte-reproducible like the rest of the pack.
DEFAULT_AMBIENCE_SOUND_REF = "ambient_loop.wav"

#: What the pre-fix builds seeded.  A database written by one of them holds a
#: rule bound to a file that no longer ships, so it is repaired in place.
_DEAD_DEFAULT_SOUND_REFS = frozenset({"computalk1.wav", "Computalk1.wav"})


def default_ambience_rules() -> list[AmbienceRule]:
    """The fresh-install rule set (T-1455): one enabled loop at 0.01.

    Unlike :func:`rule_templates`, this is NOT an inert template: it is the
    default the operator asked for ("enabled by default, 0.01 volume,
    immediately"), so it ships enabled and at a volume that is present.
    """
    return [
        AmbienceRule(id=DEFAULT_AMBIENCE_RULE_ID, name="Ambience",
                     sound_ref=DEFAULT_AMBIENCE_SOUND_REF,
                     trigger=TRIGGER_ALWAYS, repeat=REPEAT_LOOP,
                     enabled=True, volume=0.01,
                     fade_in_ms=DEFAULT_FADE_MS, fade_out_ms=DEFAULT_FADE_MS),
    ]


def is_fresh_database(store: AmbienceStore) -> bool:
    """A database where ambience was never configured and never decided.

    "Fresh" means: no rules at all AND no recorded start/stop decision.
    The decision row is the line: a user who started or stopped ambience
    (or both) has made an explicit choice and must not have it overwritten,
    even if every rule is deleted.
    """
    with store._lock, store._connect() as conn:  # noqa: SLF001 - same module
        rules = conn.execute(
            f"SELECT 1 FROM {AMBIENCE_TABLE} LIMIT 1"  # nosec B608 - closed table constant
        ).fetchone()
        decision = conn.execute(
            f"SELECT 1 FROM {WEATHER_SETTINGS_TABLE} WHERE key = ?",  # nosec B608 - closed table constant
            (SETTING_RUNTIME_ENABLED,)).fetchone()
    return rules is None and decision is None


def _ref_resolves(ref: str) -> bool:
    """Does this stored ref name a file the app can actually play?"""
    from fastprompter.core.sound_library import resolve_sound_ref

    return resolve_sound_ref(ref) is not None


def repair_dead_default_ref(store: AmbienceStore, resolver=None) -> bool:
    """Re-point the shipped default if it names a file that does not ship.

    A database written by a pre-T-1501 build holds the default rule bound to
    ``computalk1.wav``, which the audio cleanup deleted.  Seeding is
    one-shot, so without this the rule would stay dead for every existing
    install: the bed would be silent forever and only a fresh data root would
    ever play again.  Returns True when it changed something.

    Only the shipped default id is touched, and only when the ref is one of
    the old defaults AND provably resolves to nothing.  A user who has a file
    of that name in their own addon folder keeps their working rule, and no
    rule the user created is ever rewritten.

    Only ``sound_ref`` is rewritten.  The rule's NAME is left exactly as
    stored: a user who renamed the default ("Night bed") keeps that name, and
    the pre-fix default's name is already the shipped one anyway.  Rewriting
    the name would be a second, unrequested change to the user's settings on
    top of the one that is actually broken.
    """
    resolve = resolver or _ref_resolves
    replacement = default_ambience_rules()[0]
    for rule in store.load_rules():
        if rule.id != DEFAULT_AMBIENCE_RULE_ID:
            continue
        if rule.sound_ref not in _DEAD_DEFAULT_SOUND_REFS:
            continue
        try:
            if resolve(rule.sound_ref):
                continue        # it works here; leave the user's rule alone
        except Exception:
            continue            # cannot prove it is dead, so do not touch it
        rule.sound_ref = replacement.sound_ref
        store.upsert_rule(rule)
        return True
    return False


def ensure_default_rules(store: AmbienceStore, resolver=None) -> bool:
    """Seed the fresh-install default once (T-1455). Returns True on seed.

    Idempotent and race-tolerant: the check and the insert run in one
    immediate transaction, and once the default is written the database is
    no longer fresh, so nothing is ever inserted twice or resurrected.

    Before seeding, :func:`repair_dead_default_ref` fixes a default that a
    pre-T-1501 build already seeded against a deleted file.
    """
    repair_dead_default_ref(store, resolver)
    rules = default_ambience_rules()
    with store._lock, store._connect() as conn:  # noqa: SLF001 - same module
        conn.execute("BEGIN IMMEDIATE")
        try:
            seeded = conn.execute(
                f"SELECT 1 FROM {AMBIENCE_TABLE} LIMIT 1"  # nosec B608 - closed table constant
            ).fetchone()
            decision = conn.execute(
                f"SELECT 1 FROM {WEATHER_SETTINGS_TABLE} WHERE key = ?",  # nosec B608 - closed table constant
                (SETTING_RUNTIME_ENABLED,)).fetchone()
            if seeded is not None or decision is not None:
                conn.rollback()
                return False
            rule = rules[0]
            conn.execute(
                f"INSERT INTO {AMBIENCE_TABLE}(id, position, payload) "  # nosec B608 - closed table constant
                "VALUES(?, 0, ?)",
                (rule.id, json.dumps(rule.to_dict(), separators=(",", ":"))))
            conn.execute(
                f"INSERT INTO {WEATHER_SETTINGS_TABLE}(key, value) VALUES(?, ?)",  # nosec B608 - closed table constant
                (SETTING_RUNTIME_ENABLED, "True"))
            conn.commit()
        except Exception:
            conn.rollback()
            raise
    return True


#: Templates offered by the UI.  They ship DISABLED and without a sound: a
#: template the user has not configured must never start making noise.
def rule_templates() -> list[AmbienceRule]:
    return [
        AmbienceRule(id=new_rule_id(), name="Always ambience", sound_ref="",
                     trigger=TRIGGER_ALWAYS, repeat=REPEAT_LOOP,
                     enabled=False, volume=0.4,
                     fade_in_ms=DEFAULT_FADE_MS, fade_out_ms=DEFAULT_FADE_MS),
        AmbienceRule(id=new_rule_id(), name="Sunday ambience", sound_ref="",
                     trigger="WEEKDAY", weekday="sunday", repeat=REPEAT_LOOP,
                     enabled=False, volume=0.4,
                     fade_in_ms=DEFAULT_FADE_MS, fade_out_ms=DEFAULT_FADE_MS),
        AmbienceRule(id=new_rule_id(), name="Rain ambience", sound_ref="",
                     trigger="WEATHER", weather="rain", repeat=REPEAT_LOOP,
                     enabled=False, volume=0.4,
                     fade_in_ms=DEFAULT_FADE_MS, fade_out_ms=DEFAULT_FADE_MS),
    ]


class AmbienceStore:
    """Durable ambience rules + the opt-in weather location."""

    def __init__(self, db_path: str | None = None) -> None:
        if db_path is None:
            from fastprompter.utils.paths import get_data_dir

            db_path = os.path.join(get_data_dir(), AMBIENCE_DB_NAME)
        self.db_path = db_path
        parent = os.path.dirname(os.path.abspath(db_path))
        if parent:
            os.makedirs(parent, exist_ok=True)
        self._lock = threading.RLock()
        self._ensure_schema()

    def _connect(self) -> sqlite3.Connection:
        from fastprompter.core.state import connect_app_db

        return connect_app_db(self.db_path)

    def _ensure_schema(self) -> None:
        with self._lock, self._connect() as conn:
            conn.execute(
                f"CREATE TABLE IF NOT EXISTS {AMBIENCE_TABLE} ("
                "id TEXT PRIMARY KEY, position INTEGER NOT NULL DEFAULT 0,"
                "payload TEXT NOT NULL)")
            conn.execute(
                f"CREATE TABLE IF NOT EXISTS {WEATHER_SETTINGS_TABLE} ("
                "key TEXT PRIMARY KEY, value TEXT NOT NULL)")

    # -- rules ---------------------------------------------------------------

    def load_rules(self) -> list[AmbienceRule]:
        with self._lock, self._connect() as conn:
            rows = conn.execute(
                f"SELECT payload FROM {AMBIENCE_TABLE} ORDER BY position, id"  # nosec B608 - closed table constant
            ).fetchall()
        rules: list[AmbienceRule] = []
        for (payload,) in rows:
            rule = self._decode(payload)
            if rule is not None:
                rules.append(rule)
        return rules

    @staticmethod
    def _decode(payload: str) -> AmbienceRule | None:
        """One stored row, or None when its bytes are not a readable rule."""
        try:
            raw = json.loads(payload)
        except (TypeError, ValueError):
            return None
        if isinstance(raw, dict) and raw.get("id"):
            return AmbienceRule.from_dict(raw)
        return None

    def save_rules(self, rules: list[AmbienceRule]) -> None:
        """Replace the whole rule set in one transaction (stable ids kept)."""
        payloads = [(rule.id, index, json.dumps(rule.to_dict(),
                                                separators=(",", ":")))
                    for index, rule in enumerate(rules)]
        with self._lock, self._connect() as conn:
            conn.execute("BEGIN IMMEDIATE")
            try:
                conn.execute(f"DELETE FROM {AMBIENCE_TABLE}")  # nosec B608 - closed table constant
                conn.executemany(
                    f"INSERT INTO {AMBIENCE_TABLE}(id, position, payload) "
                    "VALUES(?, ?, ?)", payloads)  # nosec B608 - closed table constant
                conn.commit()
            except Exception:
                conn.rollback()
                raise

    def _mutate(self, apply):
        """One atomic read-decide-write over the authoritative rows.

        W2-002 (audit/18) found two data-loss mechanisms sharing one root
        cause: the read-modify-write helpers called ``load_rules`` (which
        released the store lock and dropped unreadable rows) and then replaced
        the ENTIRE table through ``save_rules``. Two stores over one file each
        held a private RLock, so a second writer's stale snapshot deleted the
        first writer's accepted update; and an unrelated edit converted a
        corrupt row into a deletion, destroying its recovery evidence.

        ``BEGIN IMMEDIATE`` makes this the single writer for the duration, the
        authoritative rows are read INSIDE it, and rows whose bytes do not
        decode are re-published verbatim instead of being dropped.
        """
        with self._lock, self._connect() as conn:
            conn.isolation_level = None
            conn.execute("BEGIN IMMEDIATE")
            try:
                rows = conn.execute(
                    f"SELECT id, position, payload FROM {AMBIENCE_TABLE} "  # nosec B608 - closed table constant
                    "ORDER BY position, id").fetchall()
                rules: list[AmbienceRule] = []
                # (id, position, payload) for rows that cannot be decoded.
                damaged: list[tuple[str, int, str]] = []
                for row_id, position, payload in rows:
                    rule = self._decode(payload)
                    if rule is None:
                        damaged.append((row_id, position, payload))
                    else:
                        rules.append(rule)

                updated = apply(rules)

                payloads = [(rule.id, index, json.dumps(rule.to_dict(),
                                                        separators=(",", ":")))
                            for index, rule in enumerate(updated)]
                # Damaged rows keep their own position value: their contents
                # are unreadable, so the ordinal carries no meaning, but the
                # bytes must survive untouched. ID is the tie-breaker in the
                # ordering query, so a shared position is harmless.
                payloads.extend(damaged)

                conn.execute(f"DELETE FROM {AMBIENCE_TABLE}")  # nosec B608 - closed table constant
                if payloads:
                    conn.executemany(
                        f"INSERT INTO {AMBIENCE_TABLE}(id, position, payload) "
                        "VALUES(?, ?, ?)", payloads)  # nosec B608 - closed table constant
                conn.execute("COMMIT")
                return updated
            except BaseException:
                conn.execute("ROLLBACK")
                raise

    def upsert_rule(self, rule: AmbienceRule) -> list[AmbienceRule]:
        def apply(rules: list[AmbienceRule]) -> list[AmbienceRule]:
            for index, existing in enumerate(rules):
                if existing.id == rule.id:
                    rules[index] = rule
                    return rules
            rules.append(rule)
            return rules

        return self._mutate(apply)

    def delete_rule(self, rule_id: str) -> list[AmbienceRule]:
        return self._mutate(
            lambda rules: [rule for rule in rules if rule.id != rule_id])

    def duplicate_rule(self, rule_id: str) -> list[AmbienceRule]:
        def apply(rules: list[AmbienceRule]) -> list[AmbienceRule]:
            for rule in list(rules):
                if rule.id == rule_id:
                    clone = AmbienceRule.from_dict(rule.to_dict())
                    clone.id = new_rule_id()
                    clone.name = f"{rule.name} (copy)"
                    clone.enabled = False
                    rules.append(clone)
                    break
            return rules

        return self._mutate(apply)

    # -- weather opt-in --------------------------------------------------------

    def weather_config(self) -> dict:
        with self._lock, self._connect() as conn:
            rows = dict(conn.execute(
                f"SELECT key, value FROM {WEATHER_SETTINGS_TABLE}").fetchall())  # nosec B608 - closed table constant
        return {
            "enabled": rows.get(SETTING_WEATHER_ENABLED, "False") == "True",
            "label": rows.get(SETTING_WEATHER_LABEL, ""),
            "latitude": _as_float(rows.get(SETTING_WEATHER_LAT)),
            "longitude": _as_float(rows.get(SETTING_WEATHER_LON)),
        }

    def set_weather_config(self, *, enabled: bool, label: str = "",
                           latitude=None, longitude=None) -> dict:
        """Persist the opt-in and the user-typed location.

        Enabling without a usable coordinate pair is refused: an enabled
        weather trigger that cannot fetch anything would be a lie in the UI.
        """
        lat, lon = _as_float(latitude), _as_float(longitude)
        if enabled and (lat is None or lon is None):
            enabled = False
        rows = {
            SETTING_WEATHER_ENABLED: "True" if enabled else "False",
            SETTING_WEATHER_LABEL: str(label or ""),
            SETTING_WEATHER_LAT: "" if lat is None else repr(lat),
            SETTING_WEATHER_LON: "" if lon is None else repr(lon),
        }
        with self._lock, self._connect() as conn:
            conn.executemany(
                f"INSERT INTO {WEATHER_SETTINGS_TABLE}(key, value) VALUES(?, ?)"  # nosec B608 - closed table constant
                " ON CONFLICT(key) DO UPDATE SET value=excluded.value",
                list(rows.items()))
        return self.weather_config()

    # -- desired runtime state -------------------------------------------------

    def runtime_enabled(self) -> bool:
        """Does the user want ambience running?  Default: no recorded decision.

        An absent decision row reads False (fail-closed), but a fresh
        install no longer stays silent: :func:`ensure_default_rules` seeds
        the T-1455 ambience default and this wish together at startup.
        """
        with self._lock, self._connect() as conn:
            row = conn.execute(
                f"SELECT value FROM {WEATHER_SETTINGS_TABLE} WHERE key = ?",  # nosec B608 - closed table constant
                (SETTING_RUNTIME_ENABLED,)).fetchone()
        return bool(row) and row[0] == "True"

    def set_runtime_enabled(self, enabled: bool) -> bool:
        """Record the user's explicit start/stop decision."""
        value = "True" if enabled else "False"
        with self._lock, self._connect() as conn:
            conn.execute(
                f"INSERT INTO {WEATHER_SETTINGS_TABLE}(key, value) VALUES(?, ?)"  # nosec B608 - closed table constant
                " ON CONFLICT(key) DO UPDATE SET value=excluded.value",
                (SETTING_RUNTIME_ENABLED, value))
        return bool(enabled)

    def is_fresh_database(self) -> bool:
        return is_fresh_database(self)

    def ensure_default_rules(self) -> bool:
        return ensure_default_rules(self)


def _as_float(value) -> float | None:
    try:
        if value is None or value == "":
            return None
        number = float(value)
    except (TypeError, ValueError):
        return None
    return number if -180.0 <= number <= 180.0 else None
