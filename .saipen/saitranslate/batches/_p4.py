PH = re.compile(r'\{[^{}]*\}|%[sd]')
ENT = re.compile(r'&[a-z]+;')
errs = []
for k, v in zip(keys, T):
    if not v.strip():
        errs.append(('EMPTY', k))
    if sorted(PH.findall(k)) != sorted(PH.findall(v)):
        errs.append(('PH', k, PH.findall(k), PH.findall(v)))
    if sorted(ENT.findall(k)) != sorted(ENT.findall(v)):
        errs.append(('ENT', k))
    if k.count('\t') != v.count('\t'):
        errs.append(('TAB', k))
    if k.count('\n') != v.count('\n'):
        errs.append(('NL', k, k.count('\n'), v.count('\n')))
    for em in ('⏰', '⚠', '⚡', '✏', '✓', '✨', '⬇', '𝗕', '🎭', '👁', '📁', '📂',
               '📄', '📊', '📋', '📝', '📥', '🔄', '🔌', '🔍', '🔓', '🔗', '🔼', '🗂', '🗔', '🧩'):
        if k.count(em) != v.count(em):
            errs.append(('EMO', k, em))
    if k.count('·') != v.count('·'):
        errs.append(('DOT', k))
    for p in ('data/files/_trash/', '.url', '```'):
        if k.count(p) != v.count(p):
            errs.append(('TOK', k, p))

if errs:
    for e in errs[:40]:
        print('FAIL', e)
    sys.exit(1)

