"""Fail the build when the shipped sound folder drifts from the manifest.

The app can play three separate audio layers:

1. ``src/fastprompter/sound/`` -- the shipped fallback.  Every WAV here is
   generated by ``tools/generate_redistributable_sounds.py`` or is an original
   operator asset listed in ``sounds-redistributable.manifest``.
2. the user's managed library under ``<user-data>/sound_library`` -- imported
   by the user, never packaged.
3. the addon root under ``<user-data>/addon/sounds`` -- a pack the user points
   at, never packaged.

Only layer 1 rides in a release, so only layer 1 needs an allowlist.  A WAV in
that folder which the manifest does not name is either a forgotten deletion or
a reintroduction of third-party audio; both must stop the build rather than
ship.  Audio anywhere ELSE in the repository is the same failure -- a snapshot
copy under ``.saipen/`` already re-published a removed pack once -- so the
guard also rejects every audio file outside ``src/fastprompter/sound/``.
This is the same guard SAIPLAN uses (``scripts/verify_release.py``).

Usage:
    python tools/verify_sound_allowlist.py [--root .]
"""

from __future__ import annotations

import argparse
import io
import sys
import zipfile
from pathlib import Path

SOUNDS_REL = Path("src/fastprompter/sound")
MANIFEST_REL = Path("sounds-redistributable.manifest")
AUDIO_SUFFIXES = {".wav", ".mp3", ".ogg", ".flac"}
ARCHIVE_SUFFIXES = {".zip"}
MAX_ARCHIVE_BYTES = 200 * 1024 * 1024
MAX_ARCHIVE_DEPTH = 4
MAX_ARCHIVE_ENTRIES = 20000
# Directories only consulted when the tree is not under Git control.  A git
# checkout is enumerated by Git itself (see published_audio), which is exact:
# ignored scratch trees are not coverage, but anything a push would publish is.
SKIP_DIRS = {".git", "node_modules", ".venv", "venv", "__pycache__", "build", "dist"}


def read_manifest(root: Path) -> list[str]:
    manifest = root / MANIFEST_REL
    if not manifest.is_file():
        raise SystemExit(f"sound allowlist missing: {manifest}")
    names: list[str] = []
    for line in manifest.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        names.append(line.replace("\\", "/"))
    return names


def shipped_wavs(root: Path) -> list[str]:
    sounds = root / SOUNDS_REL
    if not sounds.is_dir():
        raise SystemExit(f"shipped sound folder missing: {sounds}")
    # Cover every audio suffix, not just .wav: the artifact gate and Nuitka
    # both pick up .mp3/.ogg/... too, so the allowlist must name them as well
    # or a shipped file would be reported as "manifested but absent".
    return sorted(
        path.relative_to(sounds).as_posix().lower()
        for path in sounds.rglob("*")
        if path.is_file() and path.suffix.lower() in AUDIO_SUFFIXES
    )


def git_published_audio(root: Path) -> list[str] | None:
    """Audio paths Git would publish: tracked plus untracked-but-not-ignored.

    A checkout carries ignored debris -- release staging clones, worktrees,
    scratch builds -- that never reaches the remote.  Reporting those as
    leaks would train everyone to ignore the guard.  Git's own index and
    ignore rules answer the real question: what would the next push carry?
    Returns None when the tree is not a Git work tree, so the caller can fall
    back to a plain filesystem walk.
    """
    import subprocess

    try:
        proc = subprocess.run(
            ["git", "-C", str(root), "ls-files", "-z", "--cached", "--others",
             "--exclude-standard"],
            capture_output=True, check=True,
        )
    except (OSError, subprocess.CalledProcessError):
        return None
    found: list[str] = []
    for raw in proc.stdout.decode("utf-8", "surrogateescape").split("\0"):
        if not raw or Path(raw).suffix.lower() not in AUDIO_SUFFIXES:
            continue
        found.append(raw.replace("\\", "/"))
    return sorted(found)


def stray_audio(root: Path) -> list[str]:
    """Audio files that would be published anywhere but the vetted folder."""
    sounds_rel = SOUNDS_REL.as_posix()
    published = git_published_audio(root)
    if published is not None:
        return sorted(
            rel for rel in published
            if not rel.startswith(sounds_rel + "/") and (root / rel).is_file()
        )
    found: list[str] = []
    for path in root.rglob("*"):
        if not path.is_file() or path.suffix.lower() not in AUDIO_SUFFIXES:
            continue
        rel = path.relative_to(root)
        if any(part in SKIP_DIRS for part in rel.parts):
            continue
        try:
            path.relative_to(root / SOUNDS_REL)
        except ValueError:
            found.append(rel.as_posix())
    return sorted(found)


def _archive_contains_audio(data: bytes, depth: int = 0) -> bool:
    """True if ``data`` (an archive) contains any audio entry, recursively."""
    if depth > MAX_ARCHIVE_DEPTH or not data or len(data) > MAX_ARCHIVE_BYTES:
        return False
    try:
        zf = zipfile.ZipFile(io.BytesIO(data))
    except (zipfile.BadZipFile, OSError, ValueError):
        return False
    count = 0
    for info in zf.infolist():
        if info.is_dir():
            continue
        count += 1
        if count > MAX_ARCHIVE_ENTRIES:
            break
        name = info.filename
        if Path(name).suffix.lower() in AUDIO_SUFFIXES:
            return True
        if (Path(name).suffix.lower() in ARCHIVE_SUFFIXES
                and info.file_size <= MAX_ARCHIVE_BYTES):
            try:
                nested = zf.read(info)
            except (OSError, RuntimeError, zipfile.BadZipFile):
                continue
            if _archive_contains_audio(nested, depth + 1):
                return True
    return False


def archive_audio_leaks(root: Path) -> list[str]:
    """Published archives that carry audio (directly or nested)."""
    published = git_published_audio(root)
    if published is None:
        found_paths: list[str] = []
        for path in root.rglob("*"):
            if not path.is_file() or path.suffix.lower() not in ARCHIVE_SUFFIXES:
                continue
            rel = path.relative_to(root)
            if any(part in SKIP_DIRS for part in rel.parts):
                continue
            found_paths.append(rel.as_posix())
        published = found_paths
    leaks: list[str] = []
    for rel in published:
        if Path(rel).suffix.lower() not in ARCHIVE_SUFFIXES:
            continue
        full = root / rel
        try:
            if full.stat().st_size > MAX_ARCHIVE_BYTES:
                continue
            data = full.read_bytes()
        except OSError:
            continue
        if _archive_contains_audio(data):
            leaks.append(rel.replace("\\", "/"))
    return sorted(set(leaks))


def verify_sound_allowlist(root: Path | str = ".") -> int:
    """Return 0 when the shipped folder is exactly the manifest, else raise."""
    root = Path(root).resolve()
    allowed = {name.lower() for name in read_manifest(root)}
    shipped = set(shipped_wavs(root))

    extra = sorted(shipped - allowed)
    missing = sorted(allowed - shipped)
    stray = stray_audio(root)
    if extra or missing or stray:
        lines = ["shipped sound folder does not match the allowlist"]
        for name in extra:
            lines.append(f"  UNLISTED (remove it or add it to the manifest): {name}")
        for name in missing:
            lines.append(f"  MANIFESTED BUT ABSENT: {name}")
        for name in stray:
            lines.append(f"  AUDIO OUTSIDE THE SOUND FOLDER: {name}")
        lines.append(f"manifest: {root / MANIFEST_REL}")
        raise SystemExit("\n".join(lines))
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", default=".", help="repository root")
    args = parser.parse_args(argv)
    verify_sound_allowlist(args.root)
    print(f"sound allowlist OK ({len(read_manifest(Path(args.root)))} files)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
