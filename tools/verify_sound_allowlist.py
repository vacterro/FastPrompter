"""Fail the build when the shipped sound folder drifts from the manifest.

The app can play three separate audio layers:

1. ``src/fastprompter/sound/`` -- the shipped fallback.  Every WAV here is
   generated by ``tools/generate_redistributable_sounds.py`` or is an original
   operator asset listed in ``sounds-redistributable.manifest``.
2. the user's managed library under ``<user-data>/sound_library`` -- imported
   by the user, never packaged.
3. the addon root under ``<user-data>/addon/sounds`` -- a pack the user points
   at, never packaged.

Only layer 1 rides in a release, so only layer 1 needs an allowlist.  A WAV in
that folder which the manifest does not name is either a forgotten deletion or
a reintroduction of third-party audio; both must stop the build rather than
ship.  Audio anywhere ELSE in the repository is the same failure -- a snapshot
copy under ``.saipen/`` already re-published a removed pack once -- so the
guard also rejects every audio file outside ``src/fastprompter/sound/``.
This is the same guard SAIPLAN uses (``scripts/verify_release.py``).

Usage:
    python tools/verify_sound_allowlist.py [--root .]
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

SOUNDS_REL = Path("src/fastprompter/sound")
MANIFEST_REL = Path("sounds-redistributable.manifest")
AUDIO_SUFFIXES = {".wav", ".mp3", ".ogg", ".flac"}
# Snapshots and evidence directories can carry their own copy of the sound
# tree.  A repository-wide second copy is the exact way the removed packs came
# back once already, so every audio file outside SOUNDS_REL is an error.
SKIP_DIRS = {".git"}


def read_manifest(root: Path) -> list[str]:
    manifest = root / MANIFEST_REL
    if not manifest.is_file():
        raise SystemExit(f"sound allowlist missing: {manifest}")
    names: list[str] = []
    for line in manifest.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        names.append(line.replace("\\", "/"))
    return names


def shipped_wavs(root: Path) -> list[str]:
    sounds = root / SOUNDS_REL
    if not sounds.is_dir():
        raise SystemExit(f"shipped sound folder missing: {sounds}")
    return sorted(
        path.relative_to(sounds).as_posix().lower()
        for path in sounds.rglob("*")
        if path.is_file() and path.suffix.lower() == ".wav"
    )


def stray_audio(root: Path) -> list[str]:
    """Audio files anywhere in the repo other than the vetted sound folder."""
    sounds = root / SOUNDS_REL
    found: list[str] = []
    for path in root.rglob("*"):
        if not path.is_file() or path.suffix.lower() not in AUDIO_SUFFIXES:
            continue
        if any(part in SKIP_DIRS for part in path.relative_to(root).parts):
            continue
        try:
            path.relative_to(sounds)
        except ValueError:
            found.append(path.relative_to(root).as_posix())
    return sorted(found)


def verify_sound_allowlist(root: Path | str = ".") -> int:
    """Return 0 when the shipped folder is exactly the manifest, else raise."""
    root = Path(root).resolve()
    allowed = {name.lower() for name in read_manifest(root)}
    shipped = set(shipped_wavs(root))

    extra = sorted(shipped - allowed)
    missing = sorted(allowed - shipped)
    stray = stray_audio(root)
    if extra or missing or stray:
        lines = ["shipped sound folder does not match the allowlist"]
        for name in extra:
            lines.append(f"  UNLISTED (remove it or add it to the manifest): {name}")
        for name in missing:
            lines.append(f"  MANIFESTED BUT ABSENT: {name}")
        for name in stray:
            lines.append(f"  AUDIO OUTSIDE THE SOUND FOLDER: {name}")
        lines.append(f"manifest: {root / MANIFEST_REL}")
        raise SystemExit("\n".join(lines))
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", default=".", help="repository root")
    args = parser.parse_args(argv)
    verify_sound_allowlist(args.root)
    print(f"sound allowlist OK ({len(read_manifest(Path(args.root)))} files)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
