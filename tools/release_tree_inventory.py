"""Release tree inventory: NUL-safe Git status classification (A-I).

The 0.8.68 reconciliation exists because a large accumulated worktree mixed
accepted product work with scratch, runtime and generated paths, and nothing
could say which was which. This tool answers exactly that, read-only:

- every tracked modification, deletion and untracked path is recorded;
- each path is classified A-I per the release-wave contract;
- release-critical untracked paths raise explicit warnings;
- class I (UNKNOWN) never silently becomes release input.

It stages nothing, deletes nothing and writes only its report. `--strict`
exits 1 while any UNKNOWN path remains.
"""

