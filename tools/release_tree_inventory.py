def _first_dir(path: str) -> str:
    return path.split("/", 1)[0] + "/" if "/" in path else ""


def classify(path: str) -> tuple[str, str]:
    """Return (class letter, short rationale) for one repository-relative path."""
    name = path.rsplit("/", 1)[-1]
    if path == "AGENTS.md":
        return "E", "protocol bootstrap document, must be tracked (T-1241 defect 4)"
    if path.startswith(".github/"):
        return "A", "CI release infrastructure"
    if path.startswith(_SAIPEN_MACHINE_LOCAL):
        return "G", "machine-local SAIPEN in-flight state -- never release input (T-1241)"
    if path.startswith(".saipen/") or path.startswith("audit/"):
        return "E", "SAIPEN canonical memory / release evidence"
    if path in _OBSOLETE_TOOL_NAMES:
        return "H", "superseded one-off campaign probe, zero consumers (T-1370)"
    if path in GENERATED_SOURCE_FILES:
        return "D", "generated vocabulary required by tests and release"
    if path.startswith("tools/") or path.startswith("docs/"):
        return "A", "release tooling / repository documentation"
    if path in (".gitignore", ".gitattributes", ".cbmignore", "requirements.txt"):
        return "A", "repository configuration"
    if path.startswith("src/fastprompter/"):
        return "A", "accepted product source / shipped resources"
    if path.startswith("tests/") or path.startswith("tests_smoke/") or path == "conftest.py":
        return "B", "accepted test or fixture"
    if path.startswith("_res/"):
        return "C", "Nuitka-included shipped resource"
    if path.startswith(_CACHE_DIRS) or _first_dir(path) in _CACHE_DIRS or name in _CACHE_FILES:
        return "F", "build output / cache"
    if path.startswith(_RUNTIME_DIRS) or name in _RUNTIME_ROOT_NAMES or name.endswith(_RUNTIME_SUFFIXES):
        return "G", "session / runtime state"
    if path in _ROOT_ACCEPTED:
        return "A", "accepted repository document"
    if "/" not in path:
        if name in _ROOT_SCRATCH_NAMES or name.startswith(_SCRATCH_PREFIXES) or name.endswith(_SCRATCH_SUFFIXES):
            return "H", "scratch / diagnostic / temp"
    return "I", "unknown - review required"


def _parse_porcelain_v2(raw: bytes) -> list[dict]:
    """NUL-safe parse of `git status --porcelain=v2 -z --untracked-files=all`."""
    records: list[dict] = []
    tokens = raw.split(b"\0")
    index = 0
    while index < len(tokens):
        token = tokens[index]
        index += 1
        if not token:
            continue
        text = token.decode("utf-8", errors="replace")
        kind = text[:1]
        if kind == "?":
            records.append({"kind": "untracked", "status": "?", "path": text[2:]})
        elif kind in ("1", "u"):
            parts = text.split(" ", 8)
            if len(parts) < 9:
                continue
            records.append({"kind": "changed", "status": parts[1], "path": parts[8]})
        elif kind == "2":
            parts = text.split(" ", 9)
            if len(parts) < 10:
                continue
            record = {"kind": "renamed", "status": parts[1], "path": parts[9]}
            if index < len(tokens) and tokens[index]:
                record["orig_path"] = tokens[index].decode("utf-8", errors="replace")
                index += 1
            records.append(record)
        elif kind == "!":
            records.append({"kind": "ignored", "status": "!", "path": text[2:]})
        else:
            records.append({"kind": "other", "status": kind, "path": text})
    return records


def _git_status_raw(root: Path) -> bytes:
    proc = subprocess.run(
        ["git", "status", "--porcelain=v2", "-z", "--untracked-files=all"],
        cwd=str(root),
        capture_output=True,
    )
    if proc.returncode != 0:
        raise RuntimeError(
            f"git status failed ({proc.returncode}): "
            f"{proc.stderr.decode('utf-8', errors='replace')[:300]}"
        )
    return proc.stdout


def build_report(root: Path = REPO_ROOT) -> dict:
    records = _parse_porcelain_v2(_git_status_raw(root))
    entries = []
    counts = {letter: 0 for letter in CLASS_LABELS}
    warnings: list[str] = []
    for record in records:
        letter, rationale = classify(record["path"])
        counts[letter] += 1
        entry = {
            "path": record["path"],
            "kind": record["kind"],
            "status": record["status"],
            "class": letter,
            "rationale": rationale,
        }
        if "orig_path" in record:
            entry["orig_path"] = record["orig_path"]
        entries.append(entry)
        if letter in ("A", "B", "C", "D") and record["kind"] == "untracked":
            warnings.append(
                f"release-critical path is UNTRACKED and must be staged explicitly: {record['path']}"
            )
    entries.sort(key=lambda item: (item["class"], item["path"]))
    tracked = sum(1 for record in records if record["kind"] != "untracked")
    unknown = counts["I"]
    return {
        "schema_version": 1,
        "operation": "release_tree_inventory",
        "recorded_at": datetime.now(tz=UTC).strftime("%Y-%m-%dT%H:%M:%SZ"),
        "root": str(root),
        "totals": {
            "all": len(records),
            "tracked_changed": tracked,
            "untracked": len(records) - tracked,
            "unknown": unknown,
        },
        "class_counts": counts,
        "class_labels": CLASS_LABELS,
        "warnings": warnings,
        "entries": entries,
    }


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", default=str(DEFAULT_OUT))
    parser.add_argument("--strict", action="store_true", help="exit 1 while class I remains")
    args = parser.parse_args(argv)

    report = build_report()
    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    tmp = out.with_name(out.name + f".tmp{os.getpid()}")
    tmp.write_text(json.dumps(report, indent=2) + "\n", encoding="utf-8")
    os.replace(tmp, out)

    totals = report["totals"]
    print(
        f"tree inventory: {totals['all']} paths "
        f"({totals['tracked_changed']} tracked changes, {totals['untracked']} untracked)"
    )
    for letter in sorted(CLASS_LABELS):
        print(f"  {letter} {CLASS_LABELS[letter]:45s} {report['class_counts'][letter]}")
    shown = report["warnings"][:40]
    for warning in shown:
        print(f"  WARN {warning}")
    hidden = len(report["warnings"]) - len(shown)
    if hidden > 0:
        print(f"  WARN ... and {hidden} more release-critical untracked paths (full list in JSON)")
    print(f"report: {out}")
    return 1 if args.strict and totals["unknown"] else 0


if __name__ == "__main__":
    sys.exit(main())
