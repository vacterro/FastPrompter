"""Hold an AUDAPACK export to the acceptance claims it is supposed to carry.

Why this exists (SRC-139 / T-1443, handoff §04 and §05)
------------------------------------------------------
The compact export of this project reported three different things at once and
a reader could not tell them apart:

  * ``source_review_ready: true``            -- an auditor can read the source
  * ``saipen_snapshot.status: PROTOCOL_INCOMPLETE``
  * ``docs/audit/ACCEPTANCE.json`` citing nine evidence references

Nothing in the archive said whether the evidence those references name was
actually inside it.  It was not: all six distinct artifacts were absent, while
the same paths were present and valid in the live checkout.  The shortfall was
an export defect, not a historical evidence gap, and the two cannot be told
apart from the archive alone.

WHAT WAS ACTUALLY WRONG IN THE BASELINE (measured, not assumed)
--------------------------------------------------------------
``FastPrompter_30.10.26-T00-05-28.zip``:

  * ``saipen_snapshot.evidence_files_collected      = 6701``
  * ``saipen_snapshot.evidence_files_in_archive     = 6540``
  * ``saipen_snapshot.missing_required              = 161 entries``
  * ``saipen_snapshot.truncated_required_dirs       = ['.saipen/evidence']``

6540 + 161 = 6701, so the 161 are exactly the shortfall, and the single
truncated directory names its cause: ``audit_manifest.CONDITIONAL_DIRS`` caps
``evidence`` at 4000 files, the live tree holds 25,444, and the walk filled the
budget with pytest ``--basetemp`` debris.  Of the 161:

    125  under ``.saipen/evidence/t1450_fullsuite/basetemp/``  -- transient
     36  durable receipts (t1442 pair logs, t1453 logs, t1223 PNGs, ...)

All 36 durable omissions still existed on disk when this tool was written, so
nothing was destroyed; they were displaced.  That distinction is the whole
point: an omission is not a deletion, and a transient fixture must never
consume the slot a durable receipt needs.

THE THREE VERDICTS, KEPT SEPARATE
---------------------------------
``SOURCE_REVIEW_READY``      every file the inventory lists is a real member
                             and the inventory accounts for itself.
``PROTOCOL_SNAPSHOT_COMPLETE`` the protocol manifest reports no truncation and
                             no missing required path.
``ACCEPTANCE_EVIDENCE_COMPLETE`` every evidence reference in
                             ``docs/audit/ACCEPTANCE.json`` resolves inside the
                             archive with the expected bytes.

A caller may not collapse them.  Source-review readiness has never implied
protocol completeness, and protocol completeness has never implied that the
screenshots an acceptance claim rests on are in the box.

TRANSIENCE IS DECLARED, NOT GUESSED
-----------------------------------
Only pytest's own ``--basetemp`` tree is treated as disposable, because that is
the one class the repository actually generates on every run and can rebuild.
Everything else is durable by default -- the failure mode we are correcting is
durable evidence being dropped, so the default must be "keep".

Usage:
    python tools/audit_export_fidelity.py --archive path/to/export.zip
    python tools/audit_export_fidelity.py --archive export.zip --json
    python tools/audit_export_fidelity.py --write-required docs/audit/EXPORT_REQUIRED_EVIDENCE.json

Exit codes: 0 all three verdicts hold, 1 a named finding, 2 the archive or the
declaration cannot be read.  Fail-closed: an export that cannot be read is not
a passing export.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import pathlib
import sys
import zipfile

sys.stdout.reconfigure(encoding="utf-8")

REPO_ROOT = pathlib.Path(__file__).resolve().parent.parent
ACCEPTANCE = pathlib.Path("docs/audit/ACCEPTANCE.json")
INVENTORY = ".audapack/manifest.json"
PROTOCOL = "_AUDAPACK_MANIFEST.json"

#: Directories whose contents are regenerated by every test run. A path is
#: transient when a whole segment equals one of these names, so a checkout
#: nested under a differently-named root is still classified correctly.
TRANSIENT_SEGMENTS = ("basetemp",)

#: The packer's own non-exportable set, read from the protocol manifest when it
#: is present.  ``recovery/`` is non-exportable as a whole but two of its
#: subdirectories are re-included by an explicit precedence rule, so the check
#: below consults that list instead of hard-coding a prefix.  These are memory-
#: root relative, matching the protocol manifest's own spelling.
EXPORT_PRECEDENCE_ALLOW = ("recovery/log-detail", "recovery/board-compaction")

MEMORY_ROOT = ".saipen"


def _memory_relative(rel: str) -> str:
    """Strip the memory root so a declared prefix and a path compare alike."""
    return rel[len(MEMORY_ROOT) + 1:] if rel.startswith(MEMORY_ROOT + "/") else rel


def _matches_prefix(rel: str, prefixes) -> bool:
    """True when ``rel`` is ``prefix`` or lives under it, memory root ignored.

    The protocol manifest spells its exclusions as ``.saipen/recovery`` while the
    precedence rule spells its re-includes as ``recovery/log-detail``; both refer
    to the same memory root, so one side has to be normalised for them to be
    comparable at all.
    """
    bare = _memory_relative(rel)
    for prefix in prefixes:
        name = _memory_relative(str(prefix).rstrip("/"))
        if bare == name or bare.startswith(name + "/"):
            return True
    return False

IMAGE_MAGIC = (b"\x89PNG\r\n\x1a\n", b"\xff\xd8\xff", b"GIF87a", b"GIF89a", b"BM")


def _read_json(archive: zipfile.ZipFile, name: str) -> dict | None:
    try:
        return json.loads(archive.read(name))
    except (KeyError, ValueError):
        return None


def _sha256(payload: bytes) -> str:
    return hashlib.sha256(payload).hexdigest()


def _is_transient(rel: str) -> bool:
    return any(part in TRANSIENT_SEGMENTS for part in rel.split("/"))


def _is_image(payload: bytes) -> bool:
    return any(payload.startswith(magic) for magic in IMAGE_MAGIC)


def classify_reference(rel: str, names: set[str], non_exportable: list[str]) -> str:
    """Name the single reason ``rel`` is not in the archive, or '' when it is.

    The order matters: presence wins, then transience (a rebuilt fixture), then
    the precedence re-includes (a narrow durable declaration that outranks a
    broad non-exportable prefix), then the packer's declared exclusions, then
    plain absence. Reporting a reason that is really "nobody collected it" as
    "security excluded it" would be the same class of lie this tool exists to
    stop.
    """
    if rel in names:
        return ""
    if _is_transient(rel):
        return "transient_basetemp"
    if _matches_prefix(rel, EXPORT_PRECEDENCE_ALLOW):
        return "absent_despite_precedence"
    if _matches_prefix(rel, non_exportable):
        return "non_exportable_by_policy"
    return "absent_from_archive"


def required_evidence(root: pathlib.Path) -> list[dict]:
    """The dependency closure of the acceptance declarations, deterministically.

    Derived from ``ACCEPTANCE.json`` -- never hand-listed -- so a new claim
    automatically becomes a required export member.  Sorted by path and carrying
    the digest of the bytes the claim was written against: a requirement list
    that only named paths could be satisfied by a different file of the same
    name.
    """
    declaration = json.loads((root / ACCEPTANCE).read_text(encoding="utf-8"))
    seen: dict[str, dict] = {}
    for domain_id, planes in (declaration.get("domains") or {}).items():
        for plane, claim in (planes or {}).items():
            for rel in (claim or {}).get("evidence") or []:
                if rel in seen:
                    seen[rel]["declared_by"] = sorted({*seen[rel]["declared_by"],
                                                       f"{domain_id}.{plane}"})
                    continue
                target = root / rel
                seen[rel] = {
                    "path": rel,
                    "declared_by": [f"{domain_id}.{plane}"],
                    "present_in_checkout": target.is_file(),
                    "sha256": _sha256(target.read_bytes()) if target.is_file() else None,
                    "transient": _is_transient(rel),
                }
    return [seen[k] for k in sorted(seen)]


def verify_archive(archive_path: pathlib.Path, root: pathlib.Path) -> dict:
    """Compute the three verdicts independently; none may stand in for another."""
    archive = zipfile.ZipFile(archive_path)
    names = {n for n in archive.namelist() if not n.endswith("/")}

    inventory = _read_json(archive, INVENTORY)
    protocol = _read_json(archive, PROTOCOL)
    snapshot = (protocol or {}).get("saipen_snapshot") or {}

    # --- verdict 1: source review readiness -------------------------------
    source_findings: list[str] = []
    if inventory is None:
        source_findings.append(f"{INVENTORY}: missing or unparseable")
        ready = False
    else:
        listed = inventory.get("files") or []
        declared = len(listed)
        missing = [f["path"] for f in listed if f["path"] not in names]
        # The packer writes its own bookkeeping beside the payload; those files
        # are not project content and the inventory is right not to list them.
        bookkeeping = {name for name in (INVENTORY, PROTOCOL) if name in names}
        unexplained = len(names) - declared - len(bookkeeping)
        for rel in missing[:20]:
            source_findings.append(f"{rel}: listed in the inventory, absent from the archive")
        if len(missing) > 20:
            source_findings.append(f"... {len(missing) - 20} more listed-but-absent")
        counts = inventory.get("counts") or {}
        if counts.get("filesystem"):
            source_findings.append(
                "inventory_mode is not git-backed; untracked evidence cannot be accounted for")
        if unexplained > 0:
            source_findings.append(
                f"{unexplained} archive members are not in the inventory, so the "
                "inventory does not account for what it shipped")
        ready = bool(inventory.get("source_review_ready")) and not missing and unexplained <= 0

    # --- verdict 2: protocol snapshot completeness ------------------------
    protocol_findings: list[str] = []
    if protocol is None:
        protocol_findings.append(f"{PROTOCOL}: missing or unparseable")
        complete = False
    else:
        if not snapshot:
            protocol_findings.append("saipen_snapshot: absent from the protocol manifest")
        for rel in (snapshot.get("missing_required") or [])[:20]:
            cause = classify_reference(rel, names, snapshot.get("non_exportable") or [])
            protocol_findings.append(f"{rel}: required, not archived ({cause or 'absent'})")
        overflow = len(snapshot.get("missing_required") or []) - 20
        if overflow > 0:
            protocol_findings.append(f"... {overflow} more required-but-unarchived paths")
        for rel in snapshot.get("truncated_required_dirs") or []:
            protocol_findings.append(
                f"{rel}: required directory was truncated, so its evidence is incomplete")
        for rel in snapshot.get("truncated_optional_dirs") or []:
            protocol_findings.append(f"{rel}: optional directory was truncated")
        stale = snapshot.get("manifest_generated_at")
        if stale:
            protocol_findings.append(
                f"declared contract is dated {stale}; re-derive it before claiming"
                " the snapshot describes this checkout")
        complete = (bool(snapshot.get("evidence_complete"))
                    and not snapshot.get("missing_required")
                    and not snapshot.get("truncated_required_dirs"))

    # --- verdict 3: acceptance evidence completeness ----------------------
    acceptance_findings: list[str] = []
    references = required_evidence(root)
    non_exportable = snapshot.get("non_exportable") or []
    for entry in references:
        rel = entry["path"]
        cause = classify_reference(rel, names, non_exportable)
        if cause:
            acceptance_findings.append(f"{rel}: {cause}")
            continue
        payload = archive.read(rel)
        if entry["sha256"] and _sha256(payload) != entry["sha256"]:
            acceptance_findings.append(
                f"{rel}: archived bytes differ from the bytes the acceptance claim "
                f"was written against (archived {_sha256(payload)[:16]}, "
                f"claimed {entry['sha256'][:16]})")
        if rel.lower().endswith((".png", ".jpg", ".jpeg", ".gif", ".bmp")) and not _is_image(payload):
            acceptance_findings.append(
                f"{rel}: archived as an image reference but the bytes are not an image")
    acceptance_complete = bool(references) and not acceptance_findings

    return {
        "archive": str(archive_path),
        "archive_bytes": archive_path.stat().st_size,
        "members": len(names),
        "required_references": len(references),
        "SOURCE_REVIEW_READY": {"holds": ready, "findings": source_findings},
        "PROTOCOL_SNAPSHOT_COMPLETE": {"holds": complete, "findings": protocol_findings},
        "ACCEPTANCE_EVIDENCE_COMPLETE": {
            "holds": acceptance_complete, "findings": acceptance_findings},
    }


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--archive", type=pathlib.Path, default=None)
    parser.add_argument("--root", type=pathlib.Path, default=REPO_ROOT)
    parser.add_argument("--json", action="store_true")
    parser.add_argument("--write-required", type=pathlib.Path, default=None,
                        help="write the derived acceptance evidence closure")
    args = parser.parse_args(argv)

    root = args.root.resolve()

    if args.write_required:
        references = required_evidence(root)
        payload = {
            "schema_version": 1,
            "kind": "export_required_evidence",
            "derived_from": str(ACCEPTANCE).replace("\\", "/"),
            "note": ("Every entry must be present in an export that claims "
                     "ACCEPTANCE_EVIDENCE_COMPLETE. Derived, never hand-listed."),
            "transient_entries": sum(1 for e in references if e["transient"]),
            "references": references,
        }
        target = args.write_required
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(json.dumps(payload, indent=1) + "\n", encoding="utf-8")
        print(f"wrote {len(references)} required reference(s) to {target}")
        return 0

    if args.archive is None:
        print("--archive is required unless --write-required is used", file=sys.stderr)
        return 2
    if not args.archive.is_file():
        print(f"cannot read archive: {args.archive}", file=sys.stderr)
        return 2

    report = verify_archive(args.archive, root)
    if args.json:
        print(json.dumps(report, indent=1))
    else:
        print(f"archive {report['archive']} ({report['archive_bytes']} bytes, "
              f"{report['members']} members, {report['required_references']} required refs)")
        for verdict in ("SOURCE_REVIEW_READY", "PROTOCOL_SNAPSHOT_COMPLETE",
                        "ACCEPTANCE_EVIDENCE_COMPLETE"):
            info = report[verdict]
            print(f"  {verdict:30} {'HOLDS' if info['holds'] else 'FAILS'}")
            for finding in info["findings"]:
                print(f"      - {finding}")

    failed = [v for v in ("SOURCE_REVIEW_READY", "PROTOCOL_SNAPSHOT_COMPLETE",
                          "ACCEPTANCE_EVIDENCE_COMPLETE") if not report[v]["holds"]]
    return 0 if not failed else 1


if __name__ == "__main__":
    raise SystemExit(main())
